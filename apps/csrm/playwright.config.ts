/*
 * This harness exercises the development identity bridge (ADR 0003). Next never
 * overrides an already-set variable from `.env.local`, and both the webServer
 * entries below and the specs' own spawned servers inherit this process's
 * environment, so a developer's local `CSRM_AUTH_OIDC_ENABLED=true` cannot switch
 * the servers this run starts into OIDC mode.
 */
process.env.CSRM_AUTH_OIDC_ENABLED = 'false';

/*
 * Stop any Strapi dev server before running this suite.
 *
 * The run gets its own ports, its own SQLite file, and its own Next build
 * directory, but `strapi develop` has no equivalent knob for its output: both
 * this run and a dev server compile into the single `apps/backend/dist`. Running
 * them together makes one process clean that directory while the other writes
 * into it, which surfaces as `ENOTEMPTY` during "Cleaning dist dir" and leaves a
 * half-written build behind. The symptom afterwards is a mounted route
 * answering 405, which reads like an authorization or routing bug and is not
 * one; `rm -rf apps/backend/dist` and a restart clears it.
 *
 * Browsers must also be present: `npx playwright install chromium` downloads
 * both the browser and the headless shell this config launches. On the shared
 * build host they are installed once under /opt/ms-playwright and selected with
 * `PLAYWRIGHT_BROWSERS_PATH=/opt/ms-playwright`; nothing is reinstalled per run.
 *
 * A run must leave the working tree clean. Next rewrites `tsconfig.json` and
 * `next-env.d.ts` to match whichever dist directory it last built into, so the
 * isolated build below is stopped from doing either at the source: whenever
 * CSRM_NEXT_DIST_DIR is set, `next.config.ts` points Next's TypeScript setup at
 * `tsconfig.e2e.json`, an extends-only file that Next never rewrites and that
 * inherits every option from `tsconfig.json`; and `next-env.d.ts` is untracked,
 * regenerated by `next typegen` before every type check. A dirty tree after a
 * run is therefore a harness defect to fix here, never something to restore.
 */
const invocationId = randomUUID();
mkdirSync(join(tmpdir(), 'csrm-playwright-e2e'), { recursive: true });
const e2eRuntimeRoot = mkdtempSync(join(tmpdir(), 'csrm-playwright-e2e', `${invocationId}-`));
const e2eRuntimeAttestationPath = join(e2eRuntimeRoot, 'attestation.json');
const e2eRuntimeNonce = randomUUID();
writeAttestation(e2eRuntimeAttestationPath, e2eRuntimeNonce);
// The run outlasts the attestation's freshness window, so the runner keeps it fresh while it is alive (e2e-attestation-writer.ts).
if (process.env.TEST_WORKER_INDEX === undefined) keepAttestationFresh(e2eRuntimeAttestationPath, e2eRuntimeNonce);
process.once('exit', () => {
  rmSync(e2eRuntimeRoot, { recursive: true, force: true });
});
const runNames = runArtifactNames(invocationId);
const isolatedDatabaseFilename = runNames.databaseFilename;
const isolatedNextDistDir = runNames.nextDistDir;
const developmentApiToken = 'csrm-playwright-development-only';
/*
 * Both servers launch through the invoking Node, so the run keeps Node 24 across
 * Windows command shims. Windows installs keep Corepack beside node.exe. On other
 * platforms the pnpm that started this run (npm_execpath) is used, and Corepack's
 * POSIX location under lib/node_modules is the last resort.
 */
const pnpmCli = [
  join(dirname(process.execPath), 'node_modules', 'corepack', 'dist', 'pnpm.js'),
  process.env.npm_execpath && basename(process.env.npm_execpath).startsWith('pnpm') ? process.env.npm_execpath : undefined,
  join(dirname(process.execPath), '..', 'lib', 'node_modules', 'corepack', 'dist', 'pnpm.js'),
].find((candidate): candidate is string => candidate !== undefined && existsSync(candidate));
if (!pnpmCli) throw new Error('No pnpm entry point found for the Playwright web servers; run the suite through pnpm.');
const runPnpm = (args: string) => `"${process.execPath}" "${pnpmCli}" ${args}`;
/*
 * Each server takes a port from its own band, below every default ephemeral range
 * (src/lib/testing/e2e-harness-ports.ts), so no connection this run opens can already hold it.
 * Playwright refuses to start either server over a URL that already answers.
 */
const derivedStrapiOrigin = `http://127.0.0.1:${harnessPort('strapi', process.pid)}`;
const derivedWebOrigin = `http://127.0.0.1:${harnessPort('web', process.pid)}`;
const strapiOrigin = process.env.CSRM_E2E_STRAPI_ORIGIN ?? derivedStrapiOrigin;
const webOrigin = process.env.CSRM_E2E_WEB_ORIGIN ?? derivedWebOrigin;
const strapiPort = Number(new URL(strapiOrigin).port);
const webPort = Number(new URL(webOrigin).port);
const strapiHealthUrl = `${strapiOrigin}/_health`;
const strapiApiBaseUrl = `${strapiOrigin}/api`;

/*
 * Values the specs read back. The workers inherit the runner's environment, so
 * `??=` keeps the runner's values even though each worker evaluates this file
 * again with fresh identifiers of its own.
 */
process.env.CSRM_E2E_STRAPI_ORIGIN ??= strapiOrigin;
process.env.CSRM_E2E_WEB_ORIGIN ??= webOrigin;
process.env.CSRM_E2E_NEXT_DIST_DIR ??= isolatedNextDistDir;
// The build directory of the conformance spec's ordinary next dev server, named by this run.
process.env.CSRM_E2E_ORDINARY_NEXT_DIST_DIR ??= runNames.ordinaryNextDistDir;
process.env.CSRM_E2E_DEVELOPMENT_API_TOKEN ??= developmentApiToken;
// The web server's attestation nonce, so the client-chunk scan can prove the build never inlined it.
process.env.CSRM_E2E_ATTESTATION_NONCE_VALUE ??= e2eRuntimeNonce;

/*
 * The run's throwaway database, its attachment store beside it, and its builds (SR-09; IN-607): removed when the run
 * passes, kept together for debugging, with their paths printed, when it fails or is interrupted or when
 * CSRM_E2E_KEEP_ARTIFACTS=1 asks for them, so a kept database never references files that are gone. Only the runner does this. It exits after Playwright has stopped both servers, and its
 * names are the ones the servers were given; a worker evaluates this file with an id of its own that
 * names nothing on disk. Each path is this run's own and listed exactly, so files another run may
 * still be using are never touched.
 */
if (process.env.TEST_WORKER_INDEX === undefined) {
  const runArtifacts = runArtifactPaths({ strapiDir: join(__dirname, '..', 'backend'), webDir: __dirname, names: runNames });
  process.once('exit', (exitCode) => {
    const present = runArtifacts.filter((path) => existsSync(path));
    if (present.length === 0) return;
    const disposition = runArtifactDisposition(exitCode, process.env[KEEP_ARTIFACTS_VARIABLE] === '1');
    const report = (message: string) => writeSync(2, `\n[harness] ${message}\n${present.map((path) => `  ${path}`).join('\n')}\n`);
    if (disposition !== 'remove') {
      report(disposition === 'keep-failed'
        ? `The run exited ${exitCode}, so its database, attachment store and builds are kept for debugging:`
        : `${KEEP_ARTIFACTS_VARIABLE}=1 keeps the run's database, attachment store and builds:`);
      return;
    }
    const failures: string[] = [];
    for (const path of present) {
      try {
        rmSync(path, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 });
      } catch (error) {
        failures.push(`${path} (${(error as NodeJS.ErrnoException).code ?? 'error'})`);
      }
    }
    if (failures.length > 0) writeSync(2, `\n[harness] Could not remove:\n${failures.map((failure) => `  ${failure}`).join('\n')}\n`);
  });
}

