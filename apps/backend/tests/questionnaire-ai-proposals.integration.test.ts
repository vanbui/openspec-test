  try {
    refused = await harness.retryProposalJobFixture(second, jobId).catch((error: Error) => error);
  } finally {
    restore();
  }
  assert.ok(refused instanceof Error || refused.status >= 500, `THE_FAILED_COMMIT_WAS_NOT_REFUSED: ${JSON.stringify(refused)}`);
  const read = await harness.getProposalJobFixture(bob, jobId);
  assert.equal(read.status, 200, "THE_FAILED_JOB_WAS_REMOVED");
  assert.deepEqual([(read.data as Json).status, (read.data as Json).failureCode, (read.data as Json).attempt, (read.data as Json).canRetry], ["failed", "PROVIDER_UNAVAILABLE", 1, true], "THE_FAILED_JOB_WAS_NOT_PUT_BACK");
