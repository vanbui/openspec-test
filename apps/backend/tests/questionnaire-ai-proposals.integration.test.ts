type Harness = Awaited<typeof harnessPromise>;
type Json = Record<string, unknown>;

/* Jane's note, which Bob marks as changing the AI inputs: the deterministic provider's rule W1 reads `offshore`. */
const OFFSHORE_NOTE = "Jane: the vendor now uses an offshore support team with administrator access to the payroll system.";
const GENERATED_AT = "2026-08-20T00:00:00.000Z";

/*
 * A UAT-A-like request whose released, submitted questionnaire was generated by the AI before any note was marked: one
 * completed questionnaire-generation run that included no note, the run the analyst's `generation.runId` names.
 */
async function seedGeneratedQuestionnaire(harness: Harness, label: string): Promise<{ requestId: string; questionnaireId: string; generationRunId: string }> {
  const { requestId, questionnaireId } = await harness.seedUatALikeRequest(label);
  const built = await harness.buildAssessmentContextFixture({ operation: "questionnaire-generation", requestId });
  const generationRunId = await harness.createAiRunFixture({
    operation: "questionnaire-generation", initiatedBy: harness.users.analyst, providerName: "deterministic-questionnaire", providerVersion: "1",
    assessmentRequest: requestId, questionnaire: questionnaireId, contextSummary: built.context.summary,
  });
  await harness.completeAiRunFixture(generationRunId, { schemaVersion: 2, proposal: { questions: [] }, adjustments: [] });
  await harness.updateFixtureDocument("api::csrm-questionnaire.csrm-questionnaire", questionnaireId, {
    generatedDate: GENERATED_AT, generatedBy: harness.users.analyst, providerName: "deterministic-questionnaire", providerVersion: "1",
  });
  return { requestId, questionnaireId, generationRunId };
}

/* Jane's offshore-support note, marked as changing the AI inputs (Phase 13 D-27). */
async function markOffshoreNote(harness: Harness, requestId: string): Promise<string> {
  const [noteId] = await harness.seedRequestNotes(requestId, [
    { part: "requestor", sequence: 1, postedAt: "2026-09-01T00:00:00.000Z", body: OFFSHORE_NOTE, changesAiInputs: true },
  ]);
  return noteId;
}

/* Every question row as stored (text, help, type, options, answer, timestamps), and the release fact. */
async function questionnaireFacts(harness: Harness, questionnaireId: string): Promise<{ questions: Json[]; releasedAt: unknown; releasedBy: unknown }> {
  const questionnaire = await harness.getQuestionnaire(questionnaireId);
  assert.ok(questionnaire, "QUESTIONNAIRE_NOT_FOUND");
  const questions = ((questionnaire.questions ?? []) as Json[]).map((row) => ({ ...row })).sort((left, right) => String(left.documentId).localeCompare(String(right.documentId)));
  const releasedBy = questionnaire.releasedBy as Json | null | undefined;
  return { questions, releasedAt: questionnaire.releasedAt, releasedBy: releasedBy && typeof releasedBy === "object" ? releasedBy.documentId : releasedBy ?? null };
}

async function governanceLog(harness: Harness, questionnaireId: string): Promise<Json[]> {
  return ((await harness.getQuestionnaire(questionnaireId))?.governanceLog ?? []) as Json[];
}

/* Starts a questionnaire-wide proposal as `analystId` and follows it to its end. */
async function proposeAndWait(harness: Harness, analystId: string, questionnaireId: string, body?: unknown): Promise<Json> {
  const started = await harness.startQuestionnaireProposalsFixture(analystId, questionnaireId, body);
  assert.equal(started.status, 202, `PROPOSALS_NOT_STARTED: ${JSON.stringify(started)}`);
  return harness.waitForProposalJobFixture(String(started.data?.jobId));
}

async function readJson(harness: Harness, path: string, identity: string, diagnostic: string): Promise<Json> {
  const response = await harness.request({ path, identity });
  assert.equal(response.status, 200, `${diagnostic}: ${await response.clone().text()}`);
  return ((await response.json()) as { data: Json }).data;
}

