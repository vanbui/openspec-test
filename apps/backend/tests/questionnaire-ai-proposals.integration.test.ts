const MFA_QUESTION = "Is MFA enforced for privileged and federated identities, including break-glass accounts?";
const PLAIN_QUESTION = "Which team owns the payroll platform day to day?";
const PAYMENT_SECTION = { key: "payment", title: "Payment processing", order: 1 };

async function questionnaireRequest(harness: Harness, path: string, identity: string, method: string, body?: unknown): Promise<Response> {
  return harness.request({ path, identity, init: { method, ...(body === undefined ? {} : { headers: { "content-type": "application/json" }, body: JSON.stringify(body) }) } });
}

/* The question row with this text, as stored. */
async function questionByText(harness: Harness, questionnaireId: string, text: string): Promise<Json> {
  const row = ((await harness.getQuestionnaire(questionnaireId))?.questions as Json[] | undefined ?? []).find((question) => question.questionText === text);
  assert.ok(row, `QUESTION_NOT_FOUND: ${text}`);
  return row;
}

/*
 * The UAT-A-like questionnaire returned to analyst review (its answers drafts again), with two questions Bob added and
 * nobody answered: the MFA question rule R1 rewrites, and one with no glossary term.
 */
async function seedAnalystReview(harness: Harness, label: string): Promise<{ requestId: string; questionnaireId: string; mfaId: string; plainId: string }> {
  const { analyst } = harness.identities;
  const { requestId, questionnaireId } = await harness.seedUatALikeRequest(label);
  const path = `/api/v1/questionnaires/${encodeURIComponent(questionnaireId)}`;
  const returned = await questionnaireRequest(harness, `${path}/return_to_review`, analyst, "POST", { reason: "Add the identity questions first." });
  assert.equal(returned.status, 200, `RETURN_TO_REVIEW_FAILED: ${await returned.clone().text()}`);
  for (const [order, questionText] of [[5, MFA_QUESTION], [6, PLAIN_QUESTION]] as const) {
    const added = await questionnaireRequest(harness, `${path}/questions`, analyst, "POST", { questionText, answerType: "Long text", required: false, section: PAYMENT_SECTION, order });
    assert.equal(added.status, 200, `QUESTION_NOT_ADDED: ${await added.clone().text()}`);
  }
  return { requestId, questionnaireId, mfaId: String((await questionByText(harness, questionnaireId, MFA_QUESTION)).documentId), plainId: String((await questionByText(harness, questionnaireId, PLAIN_QUESTION)).documentId) };
}

async function rewriteAndWait(harness: Harness, analystId: string, questionnaireId: string, questionId: string, body?: unknown): Promise<Json> {
  const started = await harness.startQuestionRewriteFixture(analystId, questionnaireId, questionId, body);
  assert.equal(started.status, 202, `REWRITE_NOT_STARTED: ${JSON.stringify(started)}`);
  return harness.waitForProposalJobFixture(String(started.data?.jobId));
}

async function runOf(harness: Harness, runId: unknown): Promise<Json> {
  const run = await harness.getAiRun(String(runId));
  assert.ok(run, "RUN_NOT_FOUND");
  return run;
}

const refusal = (response: { status: number; reason?: string }) => ({ status: response.status, reason: response.reason });

test("a start is allowed in analyst review and on a submitted questionnaire, and refused with QUESTIONNAIRE_NOT_SUBMITTED while the Requestor answers (even over 500 characters), ASSESSMENT_STARTED and ASSESSMENT_DRAFT_IN_PROGRESS (D-06)", async () => {
  const harness = await harnessPromise;
  const bob = harness.users.analyst;
  const review = await seedAnalystReview(harness, "STATE-REVIEW");
  assert.equal((await proposeAndWait(harness, bob, review.questionnaireId)).status, "completed", "ANALYST_REVIEW_START_NOT_ALLOWED");
  const submitted = await harness.seedUatALikeRequest("STATE-SUBMITTED");
  assert.equal((await proposeAndWait(harness, bob, submitted.questionnaireId)).status, "completed", "SUBMITTED_START_NOT_ALLOWED");

  // Released, and Jane has a draft answer again: the state refusal comes before the instruction's (Pitfall 1).
  const answering = await harness.seedUatALikeRequest("STATE-ANSWERING");
  const fallback = await questionByText(harness, answering.questionnaireId, "Has the pay-run fallback been tested?");
  await harness.updateFixtureDocument("api::csrm-question.csrm-question", String(fallback.documentId), { answer: { schemaVersion: 1, value: "yes", state: "draft", updatedAt: "2026-09-02T00:00:00.000Z" } });
  assert.deepEqual(refusal(await harness.startQuestionnaireProposalsFixture(bob, answering.questionnaireId, { instruction: "x".repeat(501) })), { status: 409, reason: "QUESTIONNAIRE_NOT_SUBMITTED" });
  const optional = await questionByText(harness, answering.questionnaireId, "Other recovery notes?");
  assert.deepEqual(refusal(await harness.startQuestionRewriteFixture(bob, answering.questionnaireId, String(optional.documentId))), { status: 409, reason: "QUESTIONNAIRE_NOT_SUBMITTED" });

  const assessed = await harness.seedUatALikeRequest("STATE-ASSESSED");
  await harness.createAssessmentFixture({ assessmentNumber: "ASSESS-PROPOSALS-STATE", assessmentStatus: "draft", assessmentRequest: assessed.requestId });
  assert.deepEqual(refusal(await harness.startQuestionnaireProposalsFixture(bob, assessed.questionnaireId)), { status: 409, reason: "ASSESSMENT_STARTED" });

  const drafting = await harness.seedUatALikeRequest("STATE-DRAFTING");
  await harness.withHeldAssessmentDraftProvider(async (reached) => {
    const queued = await questionnaireRequest(harness, `/api/v1/questionnaires/${encodeURIComponent(drafting.questionnaireId)}/generate_assessment`, harness.identities.analyst, "POST");
    assert.equal(queued.status, 202, `DRAFT_NOT_QUEUED: ${await queued.clone().text()}`);
    await reached;
    assert.deepEqual(refusal(await harness.startQuestionnaireProposalsFixture(bob, drafting.questionnaireId)), { status: 409, reason: "ASSESSMENT_DRAFT_IN_PROGRESS" });
  });
  for (let poll = 0; poll < 100 && !(await harness.getRequest(drafting.requestId))?.assessment; poll += 1) await new Promise((resolve) => setTimeout(resolve, 50));

  for (const { questionnaireId } of [answering, assessed, drafting]) {
    assert.deepEqual(await harness.activeProposalJobsFixture(questionnaireId), [], "A_REFUSED_START_QUEUED_A_JOB");
    assert.deepEqual((await harness.listQuestionnaireRunsFixture(questionnaireId)).filter((run) => run.operation !== "assessment-draft"), [], "A_REFUSED_START_CREATED_A_RUN");
  }
});

