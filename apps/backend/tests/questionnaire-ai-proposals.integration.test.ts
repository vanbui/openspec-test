/** A text file of exactly `characters` characters, distinct per seed (14-10's fixture). */
const textFile = (seed: string, characters: number): Buffer => Buffer.from(`${seed} vendor access review. `.repeat(Math.ceil(characters / 20)).slice(0, characters), "utf8");

/* Jane uploads two 20,000-character text files and Bob includes both in the AI inputs (Phase 14's routes). */
async function includeTwoLargeFiles(harness: Harness, requestId: string): Promise<[string, string]> {
  const ids: string[] = [];
  for (const [seed, name] of [["First", "access-review-q1.txt"], ["Second", "access-review-q2.txt"]] as const) {
    // After submission a Requestor's file goes with a note of hers (Phase 14 D-10).
    const note = await questionnaireRequest(harness, `/api/v1/assessment_requests/${encodeURIComponent(requestId)}/notes`, harness.identities.owner, "POST", { data: { body: `The ${seed.toLowerCase()} access review is attached.` } });
    assert.equal(note.status, 200, `NOTE_FAILED: ${await note.clone().text()}`);
    const form = new FormData();
    form.set("file", new File([textFile(seed, 20_000)], name));
    form.set("noteId", String(((await note.json()) as { data: Json }).data.documentId));
    const uploaded = await harness.request({ path: attachmentsPath(requestId), identity: harness.identities.owner, init: { method: "POST", body: form } });
    assert.equal(uploaded.status, 201, `UPLOAD_FAILED: ${await uploaded.clone().text()}`);
    const attachmentId = String(((await uploaded.json()) as { data: Json }).data.documentId);
    const included = await questionnaireRequest(harness, `${attachmentsPath(requestId)}/${encodeURIComponent(attachmentId)}/ai_input`, harness.identities.analyst, "PUT", { data: { included: true } });
    assert.equal(included.status, 200, `INCLUDE_FAILED: ${await included.clone().text()}`);
    ids.push(attachmentId);
  }
  return [ids[0], ids[1]];
}

