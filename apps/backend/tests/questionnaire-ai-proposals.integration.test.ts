  const harness = await harnessPromise;
  const { requestId, questionnaireId } = await harness.seedUatALikeRequest("BE01-LAST-SLOT");
  await harness.updateFixtureDocument("api::csrm-questionnaire.csrm-questionnaire", questionnaireId, { releasedAt: null, releasedBy: null });
  for (const index of [1, 2]) {
    await harness.createFixtureDocument("api::csrm-question.csrm-question", { questionnaire: questionnaireId, questionText: `Explain support control ${index}?`, answerType: "Text", answer: null, options: { schemaVersion: 2, questionKey: `be01-${index}`, section: { key: "be01", title: "Support controls", order: 3 }, order: index, required: false } });
  }
  const built = await harness.buildAssessmentContextFixture({ operation: "questionnaire-proposals", requestId, questionnaireId });
  for (let index = 0; index < 99; index += 1) {
    const run = await harness.createAiRunFixture({ operation: "questionnaire-proposals", initiatedBy: harness.users.analyst, providerName: "deterministic-questionnaire-proposals", providerVersion: "1", assessmentRequest: requestId, questionnaire: questionnaireId, contextSummary: built.context.summary });
    await harness.completeAiRunFixture(run, { schemaVersion: 1, operation: "questionnaire-proposals", outcome: "no-change", items: [], adjustments: [] });
  }
  const questions = ((await harness.getQuestionnaire(questionnaireId))?.questions as Json[]).filter((q) => !(q.answer as Json | null)?.value);
  assert.ok(questions.length >= 2);
  await harness.withHeldQuestionnaireProposalProvider(async (hold) => {
    const first = await harness.startQuestionnaireProposalsFixture(harness.users.analyst, questionnaireId);
    assert.equal(first.status, 202);
    await hold.reached;
    const retries = await Promise.all(questions.slice(0, 2).map((q) => harness.startQuestionRewriteFixture(harness.users.secondAnalyst, questionnaireId, String(q.documentId))));
    assert.deepEqual(retries.map(({ status, reason }) => ({ status, reason })), [{ status: 409, reason: "AI_PROPOSAL_RUN_LIMIT" }, { status: 409, reason: "AI_PROPOSAL_RUN_LIMIT" }], "INFLIGHT_RESERVATION_NOT_COUNTED");
    hold.release();
    await harness.waitForProposalJobFixture(String(first.data?.jobId));
  });
  assert.equal((await harness.listQuestionnaireRunsFixture(questionnaireId)).filter((run) => run.status === "completed").length, 100);
